import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base=new URL('../',import.meta.url);
const read=f=>readFileSync(new URL(f,base),'utf8');
test('Windows NSIS configuration must bundle engine resources and never expose generic shell',()=>{
 const conf=JSON.parse(read('src-tauri/tauri.windows.conf.json'));
 assert.deepEqual(conf.bundle.targets,['nsis']);
 assert.equal(conf.bundle.active,true);
 assert.equal(conf.bundle.resources['resources/engine/'],'engine/');
 assert.match(read('src-tauri/src/engine_bridge.rs'),/resource_dir\(\)/);
 assert.match(read('src-tauri/src/engine_bridge.rs'),/node\.exe/);
 assert.doesNotMatch(read('src-tauri/src/engine_bridge.rs'),/Command::new\(.*user/);
});
test('Windows staging requires pinned SDK and performs bundled-runtime smoke',()=>{
 const script=read('scripts/stage-windows-engine.mjs');
 assert.match(script,/tempora-framework@3\.0\.0/);
 assert.match(script,/windows_smoke/);
 assert.match(script,/sha256/);
 assert.doesNotMatch(script,/https?:\/\//);
});

test('Distribution qualification asserts installed GUI startup, lockfile integrity and npm audit',()=>{
 const stage=read('scripts/stage-windows-engine.mjs');
 const installed=read('scripts/verify-windows-install.ps1');
 assert.match(stage,/--audit-level=high/);
 assert.match(stage,/lock_sha256/);
 assert.match(stage,/dependencies:inventory/);
 assert.match(installed,/INSTALLED_LOCKFILE_DIGEST_MISMATCH/);
 assert.match(installed,/INSTALLED_TAURI_GUI_EXITED_EARLY/);
 assert.match(installed,/Get-AuthenticodeSignature/);
});

test('CI enforces committed Cargo.lock and Tauri runner must use locked resolution',()=>{
 const ci=read('../../.github/workflows/desktop-foundation.yml');
 const pkg=JSON.parse(read('package.json'));
 assert.match(ci,/cargo test --locked --manifest-path src-tauri\/Cargo\.toml/);
 assert.match(ci,/cargo metadata --locked --manifest-path src-tauri\/Cargo\.toml/);
 assert.match(ci,/git diff --exit-code -- src-tauri\/Cargo\.lock/);
 assert.doesNotMatch(ci,/cargo generate-lockfile/);
 assert.doesNotMatch(ci,/contents: write/);
 assert.match(pkg.scripts['build:windows'],/tauri build .* -- --locked/);
 const lock=read('src-tauri/Cargo.lock');
 assert.match(lock,/^# This file is automatically @generated by Cargo\./);
 assert.match(lock,/^version = 4$/m);
 assert.match(lock,/name = "tempora-desktop"/);
});

test('NSIS installs Evergreen WebView2 as explicit prerequisite before launch',()=>{
 const offline=JSON.parse(read('src-tauri/tauri.windows.conf.json'));
 const online=JSON.parse(read('src-tauri/tauri.windows.online.conf.json'));
 assert.deepEqual(offline.bundle.windows.webviewInstallMode,{type:'offlineInstaller',silent:true});
 assert.deepEqual(online.bundle.windows.webviewInstallMode,{type:'embedBootstrapper',silent:true});
 assert.match(read('scripts/build-online-webview.ps1'),/tauri build --config src-tauri\/tauri\.windows\.conf\.json --config src-tauri\/tauri\.windows\.online\.conf\.json -- --locked/);
});
test('Fixed WebView2 experiment requires locally verified CAB and Cargo-locked Tauri build',()=>{
 const conf=JSON.parse(read('src-tauri/tauri.windows.fixed.conf.json'));
 assert.deepEqual(conf.bundle.windows.webviewInstallMode,
   {type:'fixedRuntime',path:'./resources/webview2-fixed/'});
 const stage=read('scripts/stage-fixed-webview.ps1');
 const build=read('scripts/build-fixed-webview.ps1');
 const diag=read('scripts/diagnose-webview2.ps1');
 assert.match(stage,/WEBVIEW_CAB_SHA256_MISMATCH/);
 assert.match(stage,/msedgewebview2\.exe/);
 assert.match(build,/stage-fixed-webview\.ps1/);
 assert.match(build,/tauri build --config src-tauri\/tauri\.windows\.conf\.json --config src-tauri\/tauri\.windows\.fixed\.conf\.json -- --locked/);
 assert.match(build,/CARGO_LOCK_MODIFIED/);
 assert.match(diag,/WebView2|webview2/i);
 const ci=read('../../.github/workflows/desktop-foundation.yml');
 assert.match(ci,/Verify Fixed WebView2 staging rejects tampered and non-CAB files/);
 assert.match(ci,/WEBVIEW_CAB_SHA256_MISMATCH/);
 assert.match(ci,/WEBVIEW_CAB_EXPANSION_FAILED/);
 const ignore=read('../../.gitignore');
 assert.match(ignore,/resources\/webview2-fixed\//);
});

